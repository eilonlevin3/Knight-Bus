#!/usr/bin/env bash
# Builds one version of the site: checks, tests, city data, then the files to publish.
# Docs: docs/release-process.md
# @req REQ-REL-1 @req REQ-REL-2 @req REQ-PWA-3
#
# Usage: scripts/build-site.sh <channel> <out-dir>
#   channel   main | debug
#   out-dir   where to put the finished site (created; replaced only when everything passed)
# Env: GTFS_ZIP      reuse an already downloaded national GTFS zip
#      SPEED_DAYS_DIR  where the daily travel-time summaries are kept between runs
#      SKIP_INSTALL  set to 1 to use the node_modules you already have (local runs)
set -euo pipefail

CHANNEL="$1"
OUT="$(mkdir -p "$2" && cd "$2" && pwd)"
SRC="$(cd "$(dirname "$0")/.." && pwd)"
cd "$SRC"

COMMIT="$(git rev-parse --short HEAD)"
echo "::group::[$CHANNEL] install, docs check, tests ($COMMIT)"
[ -n "${SKIP_INSTALL:-}" ] || npm ci --no-audit --no-fund
npm run check:docs
npm test
echo "::endgroup::"

echo "::group::[$CHANNEL] city data"
npm run build:data
echo "::endgroup::"

# A month of real travel times between stops, for the ghost (REQ-DATA-12). If it fails, the
# site is still built: ghosts then move at timetable speed.
echo "::group::[$CHANNEL] travel times"
npm run build:speeds || echo "::warning::[$CHANNEL] travel times were not built; ghosts will use the timetable"
echo "::endgroup::"

# Assemble in a temp folder; copy to OUT only at the very end, so a failure leaves nothing half-built.
TMP="$(mktemp -d)"
cp -r index.html manifest.webmanifest sw.js src icons data "$TMP/"

# Stamp the version: the app shows it, and the service worker uses it to detect updates.
cat > "$TMP/src/build.js" <<EOF
// Generated by scripts/build-site.sh. Do not edit.
export const build = { channel: '$CHANNEL', commit: '$COMMIT', builtAt: '$(date -u +%Y-%m-%dT%H:%M:%SZ)' };
EOF
sed -i "s/^const SHELL_VERSION = .*/const SHELL_VERSION = '$COMMIT';/; s/^const CHANNEL = .*/const CHANNEL = '$CHANNEL';/" "$TMP/sw.js"

if [ "$CHANNEL" = "debug" ]; then
  # A separate installable app: own name, orange icon, orange bar.
  cp icons-debug/* "$TMP/icons/"
  node -e '
    const fs = require("fs"); const f = process.argv[1];
    const m = JSON.parse(fs.readFileSync(f, "utf8"));
    Object.assign(m, { name: "Knight Bus DEBUG", short_name: "KB Debug", theme_color: "#e85d04", background_color: "#3a1600" });
    fs.writeFileSync(f, JSON.stringify(m, null, 2));
  ' "$TMP/manifest.webmanifest"
  sed -i 's/<meta name="theme-color" content="[^"]*">/<meta name="theme-color" content="#e85d04">/; s/<title>Knight Bus<\/title>/<title>Knight Bus DEBUG<\/title>/; s/content="Knight Bus">/content="KB Debug">/' "$TMP/index.html"
fi

cp -r "$TMP/." "$OUT/"
rm -rf "$TMP"
echo "[$CHANNEL] built $COMMIT into $OUT"
